CREATE TABLE IF NOT EXISTS fn_users (
 id CHAR(36) PRIMARY KEY, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, is_admin BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS fn_sessions (
 token_hash CHAR(64) PRIMARY KEY, user_id CHAR(36) NOT NULL,
 expires_at DATETIME NOT NULL,
 FOREIGN KEY (user_id) REFERENCES fn_users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS fn_records (
 kind VARCHAR(12) NOT NULL, id CHAR(36) NOT NULL, document JSON NOT NULL,
 PRIMARY KEY(kind,id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS fn_visit_slots (
 contract_id CHAR(36) NOT NULL, due_date DATE NOT NULL, report_id CHAR(36) NOT NULL UNIQUE,
 PRIMARY KEY(contract_id,due_date)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS fn_login_limits (
 bucket CHAR(64) PRIMARY KEY, attempts INTEGER NOT NULL, started_at DATETIME NOT NULL
) ENGINE=InnoDB;
